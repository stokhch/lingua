const UNIQUE_ENDINGS = [...new Set([...VERB_ENDINGS, ...NOUN_ENDINGS])].sort((a, b) => a.length - b.length);
// Словарные окончания, которые подставляем к основе
const LEM_VERB = ['ω', 'αω', 'ομαι', 'αμαι', 'ιεμαι'];
const LEM_NOUN = ['οσ', 'ο', 'ι', 'α', 'η', 'ασ', 'ησ', 'μα', 'ια', 'ιο', 'ουσ', 'υσ', 'εσ', 'ε'];
// Смена согласной на конце основы в аористе и будущем: γράψ- → γράφ-, αγόρασ- → αγοράζ-, μίλησ- → μιλ-(άω)
const ALT = [
  ['ησ', ['']], ['ασ', ['αζ', '']], ['εσ', ['', 'εν']], ['ισ', ['ιζ', 'ιν', 'ι']], ['υσ', ['υν', 'υ']],
  ['σ', ['ζ', 'ν', 'θ', 'σσ', '']], ['ξ', ['ζ', 'κ', 'γ', 'χ', 'σσ', 'γγ', 'χν', 'σκ']],
  ['εψ', ['ευ']], ['αψ', ['αυ']], ['ψ', ['φ', 'π', 'β', 'πτ', 'φτ']], ['ηθ', ['']], ['τ', ['ζ']], ['θ', ['ν', '']]
];

function alts(s) {
  const out = [];
  for (const [end, reps] of ALT) if (s.endsWith(end) && s.length > end.length + 1) for (const r of reps) out.push(s.slice(0, -end.length) + r);
  return out;
}

// Ищем словарную форму для основы. verbal — окончание точно глагольное: тогда сначала пробуем глагол.
function find(stem, verbal, onlyVerbs = false) {
  const order = onlyVerbs ? LEM_VERB : verbal ? [...LEM_VERB, ...LEM_NOUN, ''] : [...LEM_NOUN, ...LEM_VERB, ''];
  for (const e of order) { const hit = INDEX.get(stem + e); if (hit) return hit; }
  // основы с приращением и сменой согласной бывают только у глаголов
  const verbStems = [...alts(stem)];
  if (/^[εη]/.test(stem) && stem.length >= 4) verbStems.push(stem.slice(1), ...alts(stem.slice(1))); // έ-γραψ-α, ή-θελ-α
  for (const s of verbStems) for (const e of LEM_VERB) { const hit = INDEX.get(s + e); if (hit) return hit; }
  return '';
}

export function lemma(raw) {
  const w = lower(raw).replace(/[’`']/g, '').replace(/^[^\p{L}]+|[^\p{L}]+$/gu, '');
  if (!w) return '';
  if (DICT.has(w)) return w;
  const p = plain(w);
  if (FORMS[p]) return FORMS[p];
  if (INDEX.has(p)) return INDEX.get(p);
  // сначала — глагольные окончания и только глаголы (γράφ-εις → γράφω, а не γραφε-ίο),
  // затем любые окончания
  for (const end of UNIQUE_ENDINGS) {
    if (!VERBAL.has(end) || !p.endsWith(end) || p.length - end.length < 2) continue;
    const hit = find(p.slice(0, -end.length), true, true);
    if (hit) return hit;
  }
  for (const end of UNIQUE_ENDINGS) {
    if (!p.endsWith(end) || p.length - end.length < 2) continue;
    const hit = find(p.slice(0, -end.length), VERBAL.has(end));
    if (hit) return hit;
  }
  return w;
}

export function lookup(raw) {
  const l = lemma(raw);
  return { word: l, translation: DICT.get(l) || '' };
}
